import { copyFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const kit = resolve(here, "../..");
const dest = resolve(here, "../public/assets");
mkdirSync(dest, { recursive: true });

const files = [
  ["assets/models/campus_blockout.glb", "campus_blockout.glb"],
  ["data/campus.layout.json", "campus.layout.json"],
  ["data/collision.json", "collision.json"],
  ["data/interiors.json", "interiors.json"],
  ["assets/logo/hus_logo.svg", "hus_logo.svg"],
];

// GLB, collision.json and interiors.json are generated by scripts/build_blockout.py (Python stdlib only).
// If they are missing (e.g. a .gitignore dropped *.glb, or only part of the kit was copied), rebuild them.
const generated = new Set(["assets/models/campus_blockout.glb", "data/collision.json", "data/interiors.json"]);
const missing = () => files.filter(([from]) => !existsSync(resolve(kit, from))).map(([from]) => from);

function rebuild() {
  const script = resolve(kit, "scripts/build_blockout.py");
  if (!existsSync(script)) return false;
  const candidates = process.platform === "win32"
    ? [["py", ["-3", script]], ["python", [script]], ["python3", [script]]]
    : [["python3", [script]], ["python", [script]]];
  for (const [cmd, args] of candidates) {
    console.log(`Đang dựng lại mô hình: ${cmd} ${args.join(" ")}`);
    const run = spawnSync(cmd, args, { cwd: kit, stdio: ["ignore", "ignore", "inherit"], shell: false });
    if (run.error) continue; // command not found, try the next one
    if (run.status === 0) return true;
    // On Windows "python" can be the Microsoft Store stub, which exits non-zero; try the next command.
    console.error(`${cmd} không chạy được build_blockout.py (mã ${run.status}).`);
  }
  console.error(`Không chạy được Python (đã thử ${candidates.map(([cmd]) => cmd).join(", ")}).`);
  return false;
}

if (missing().some((from) => generated.has(from))) {
  console.warn(`Thiếu file sinh ra: ${missing().filter((f) => generated.has(f)).join(", ")}`);
  rebuild();
}

const stillMissing = [];
for (const [from, name] of files) {
  const source = resolve(kit, from);
  const target = resolve(dest, name);
  if (existsSync(source)) {
    copyFileSync(source, target);
    console.log("synced", name);
  } else if (existsSync(target)) {
    console.warn(`Không thấy ${from}; dùng tạm bản đã có trong web/public/assets/${name}.`);
  } else {
    stillMissing.push(from);
  }
}

if (stillMissing.length) {
  console.error(`
Thiếu: ${stillMissing.join(", ")}
Cách sửa (chạy ở thư mục ussh_hus_cli_kit, không phải web/):
  py -3 scripts/build_blockout.py      (Windows)   hoặc   python3 scripts/build_blockout.py
Nếu thư mục nằm trong một repo Git, kiểm tra xem .gitignore có bỏ qua file .glb không:
  git check-ignore -v assets/models/campus_blockout.glb
`);
  process.exit(1);
}
