import { createRequire } from 'node:module';
import { mkdirSync } from 'node:fs';
const require = createRequire(new URL('../web/package.json', import.meta.url));
const { chromium } = require('playwright');
const out = new URL('./minimap-review/', import.meta.url).pathname.replace(/^\/(\w:)/, '$1');
mkdirSync(out, {recursive:true});
const browser = await chromium.launch({channel:'chrome',args:['--use-angle=d3d11','--ignore-gpu-blocklist']});
const page = await browser.newPage({ viewport:{width:844,height:390},deviceScaleFactor:1,isMobile:true,hasTouch:true });
const errors=[];page.on('pageerror',e=>errors.push(String(e)));
await page.goto('http://127.0.0.1:4175/');
await page.waitForFunction(()=>window.__hoitu?.ready);
await page.evaluate(()=>{ window.__hoitu.storyProgress.set({introSeen:true}); window.__hoitu.go('walk'); });
await page.locator('[data-dialogue-next]').click();
await page.waitForTimeout(1000);
await page.screenshot({path:out+'/follow.png'});
await page.locator('[data-map-mode]').click();
await page.waitForTimeout(300);
await page.screenshot({path:out+'/overview.png'});
if(await page.locator('[data-map-mode]').getAttribute('aria-pressed')!=='true') throw Error('Overview toggle failed');
await page.locator('[data-map-zoom="in"]').click();
await page.waitForTimeout(250);
if(await page.locator('[data-map-mode]').getAttribute('aria-pressed')!=='false') throw Error('Zoom should restore follow');
await page.locator('.minimap-canvas').click({position:{x:75,y:65}});
await page.waitForTimeout(250);
if(!(await page.locator('.minimap-status').textContent()).includes('Đã đánh dấu')) throw Error('Waypoint not set');
const rects=await page.evaluate(()=>{const r=s=>{const a=document.querySelector(s)?.getBoundingClientRect();return a&&{x:a.x,y:a.y,w:a.width,h:a.height}};return {map:r('.minimap'),music:r('.music-dock')}});
console.log(JSON.stringify({rects,errors}));
await page.screenshot({path:out+'/waypoint.png'});
await page.setViewportSize({width:1280,height:800});await page.waitForTimeout(250);await page.screenshot({path:out+'/desktop.png'});
await browser.close();if(errors.length)process.exit(1);
